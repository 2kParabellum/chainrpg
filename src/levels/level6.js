// Данные уровня «Hit the Count»: большой квадратный зал, в центре — Под (взводной механизм на полу), посередине
// сторон — четыре гнезда. Дружочки сами не появляются: проезд по Поду выдаёт троих в одном из углов. Проехал по Поду
// цепочкой из 15 дружочков — открылся портал выхода. Здесь только данные — никакой игровой логики (Под — game/pod.js).
(function (G) {
'use strict';

// ============================================================================
//  ПЛАН ЗАЛА
//  Координаты — пиксели внутреннего квадрата (units: 'px'): 0..2400 по обеим осям, центр — (1200, 1200).
//  pillars: [cx, cy, w, h]; nests: [cx, cy].
//  В центре — Под: круг радиусом radius, по нему надо проехать цепочкой. Вокруг него круг ~700 пусто — длинной цепочке
//  нужен разгон по прямой. Колонны кольцом за ним: на диагоналях, по бокам от дорог от гнёзд к центру и в углах.
//  Гнёзда — посередине сторон, у стен.
// ============================================================================

const S = 2400, C = S / 2;
const F = 420, D = 560;           // колонны по бокам от гнезда: на F в сторону от оси, на D от стены

// четыре точки, симметричные (x, y) поворотом зала на четверть оборота: [cx, cy, w, h]
function around(x, y, w, h) {
  return [[x, y, w, h], [S - y, x, h, w], [S - x, S - y, w, h], [y, S - x, h, w]];
}

const ROOM_PLAN = {
  units: 'px',
  pillars: [
    ...around(640, 640, 110, 110),                          // диагонали
    ...around(C - F, D, 90, 90), ...around(C + F, D, 90, 90), // по бокам от каждого гнезда
    ...around(360, 360, 80, 80),                            // углы
  ],
  nests: [[C, 170], [S - 170, C], [C, S - 170], [170, C]],
  // Под: goal дружочков за один проезд — победа; после проезда взводится снова через cooldown секунд; каждое проехавшее
  // по готовому Поду звено лечится на heal своего HP (раз за проезд); проезд кончился, если gap секунд никто из цепочки
  // его не касается; ближе keepClear к центру не появляются подиумы.
  // Начало проезда по готовому Поду выдаёт dropCount дружочков, раскиданных по одному из углов зала drops
  // ([cx, cy, w, h]: левый верхний, правый верхний, правый нижний, левый нижний)
  pod: {
    at: [C, C], radius: 120, goal: 15, cooldown: 15, heal: 0.5, gap: 1, keepClear: 330,
    drops: [[380, 380, 640, 640], [S - 380, 380, 640, 640], [S - 380, S - 380, 640, 640], [380, S - 380, 640, 640]],
    dropCount: 3,
  },
};

G.level6 = {
  name: 'Hit the Count',
  blurb: 'A big square hall: drive a chain of 15 mates across the pod in the middle',
  goal: 'Drive over the pod: mates appear where the arrow points. Cross it with 15 at once',
  geometry: { kind: 'rect', width: S + 80, height: S + 80, wall: 40 },
  spawn: { room: 0, at: [C, C + 420], heading: -Math.PI / 2 }, // у самого Пода, лицом к нему
  // враги гнёзд — подвижные типы, как в «Логове», только без колесницы
  enemyPool: ['shooter', 'bull', 'scorpion', 'zombie', 'hunter'],
  enemyWeights: { shooter: 4, zombie: 2, hunter: 2, bull: 1, scorpion: 1 },
  zoneNames: ['COUNT HALL'],
  // гнёзда: с первой волны по двое, растут медленно; пауза сокращается до 11 с за 16 минут
  waves: {
    firstAt: 20, stagger: 6, interval: 24,
    ramp: { to: 11, time: 960 },
    size: { first: 2, grow: 0.075 },
    kinds: 2,
    spawnRadius: 100,
    telegraph: 4,
    maxAlive: 30,
  },
  // победа: за один проезд по Поду прошло goal дружочков; портал выхода — на самом Поде
  victory: { kind: 'podCount', label: 'POD' },
  exit: { room: 0, at: [C, C] },
  // подиумы — в случайном месте зала (не у Пода), профессии чуть чаще обычного; дружочки сами не появляются — их выдаёт Под
  padSpawn: { anywhere: true, jobs: { maxActive: 5, interval: [4, 8.8] } },
  allySpawn: { startCount: 0, maxActive: 0 },
  rooms: [ROOM_PLAN],
};
})(window.Game = window.Game || {});
