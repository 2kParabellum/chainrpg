// Данные уровня «Capture the Flags»: квадратное кольцо — скала по краям и большая скала в центре, играем в коридоре
// вокруг неё. В четырёх углах — площадки флагов, посередине сторон в нишах — гнёзда. Флаг поднят, пока на его площадке
// лежит дружочек; подняты все четыре разом — победа. Здесь только данные — никакой игровой логики (флаги — game/flags.js).
(function (G) {
'use strict';

// ============================================================================
//  ПЛАН КОЛЬЦА
//  Координаты — пиксели внутреннего квадрата (units: 'px'): 0..3200 по обеим осям, центр — (1600, 1600).
//  Скала по краям толщиной O, кроме ниш с гнёздами посередине сторон (шириной NICHE). Внутри неё — кольцо 200..3000:
//  в центре скала IN0..IN1 со срезанными лесенкой углами, вокруг — коридор шириной 780, углы кольца — квадраты 780.
//  walls / pillars / pits / spikes: [cx, cy, w, h]; nests: [cx, cy]; flags: [cx, cy].
//  План симметричен поворотом на четверть оборота: всё, что задано для северо-западного угла и северной стороны,
//  повторяется помощником around() на остальных трёх.
//  Угол: флаг в «форте» — две стенки-колонны отгораживают его от коридоров (от гнёзд), вход — со стороны центральной
//  скалы. Сторона: гнездо в нише, по краям коридора — колонны-укрытия, у центральной скалы — пропасть, по бокам от неё —
//  шипы.
// ============================================================================

const S = 3200, C = S / 2;
const O = 200;                    // скала по краям (в ней — ниши гнёзд)
const NICHE = 320;                // ширина ниши с гнездом
const IN0 = 980, IN1 = 2220;      // центральная скала
const CUT = 3, STEP = 70;         // срез её углов — лесенка из CUT ступенек по STEP

// четыре прямоугольника, симметричные (x, y) поворотом кольца на четверть оборота: [cx, cy, w, h]
function around(x, y, w, h) {
  return [[x, y, w, h], [S - y, x, h, w], [S - x, S - y, w, h], [y, S - x, h, w]];
}

// центральная скала: средняя полоса во всю ширину, сверху и снизу — по CUT полос, каждая короче на ступеньку с обеих сторон
function core() {
  const side = IN1 - IN0, out = [[C, C, side, side - 2 * CUT * STEP]];
  for (let k = 0; k < CUT; k++) {
    const w = side - 2 * (CUT - k) * STEP;
    out.push([C, IN0 + (k + 0.5) * STEP, w, STEP], [C, IN1 - (k + 0.5) * STEP, w, STEP]);
  }
  return out;
}

const SPOTS = around(560, 560, 0, 0).map(([x, y]) => [x, y]);  // флаги — в углах кольца

const ROOM_PLAN = {
  units: 'px',
  walls: [
    // скала по краям: на каждой стороне — два куска по бокам от ниши
    ...around((C - NICHE / 2) / 2, O / 2, C - NICHE / 2, O),
    ...around(S - (C - NICHE / 2) / 2, O / 2, C - NICHE / 2, O),
    ...core(),
  ],
  pillars: [
    // форт флага: стенка от наружной стены вдоль коридора гнезда и стенка поперёк — вход со стороны центра
    ...around(820, 380, 40, 360), ...around(380, 820, 360, 40),
    // укрытия по краям коридора, между гнездом и фортами
    ...around(1180, 470, 80, 80), ...around(S - 1180, 470, 80, 80),
  ],
  // у центральной скалы — пропасть: вдоль неё остаётся узкий проход
  pits: around(C, 760, 440, 110),
  // шипы по бокам от пропасти
  spikes: [...around(1290, 760, 120, 70), ...around(S - 1290, 760, 120, 70)],
  // гнёзда — в глубине ниш
  nests: around(C, 110, 0, 0).map(([x, y]) => [x, y]),
  // площадки флагов: флаг поднят, пока на площадке лежит дружочек (см. game/flags.js)
  flags: SPOTS,
};

G.level7 = {
  name: 'Capture the Flags',
  blurb: 'A square ring: four flags in the corners, four nests in between',
  goal: 'Leave a mate on each of the four flags — hold all four at once',
  geometry: { kind: 'rect', width: S + 80, height: S + 80, wall: 40 },
  spawn: { room: 0, at: [760, 2440], heading: -Math.PI / 4 }, // в юго-западном углу, у флага, лицом к выходу из форта
  // враги гнёзд — подвижные типы, как в «Hit the Count»; Скорпион (утаскивает часовых с флагов) — редкий
  enemyPool: ['shooter', 'bull', 'scorpion', 'zombie', 'hunter'],
  enemyWeights: { shooter: 4, zombie: 2, hunter: 2, bull: 1, scorpion: 0.5 },
  zoneNames: ['FLAGS'],
  // гнёзда: по одному врагу, второй — с шестой волны гнезда; пауза сокращается с 26 до 14 с за 9 минут.
  // hunt — враги волн идут к ближайшему союзнику (звену цепочки или лежачему), а не к Герою: часовых на флагах грызут
  waves: {
    firstAt: 18, stagger: 6, interval: 26,
    ramp: { to: 14, time: 540 },
    size: { first: 1, grow: 0.2 },
    kinds: 2,
    spawnRadius: 90,
    telegraph: 4,
    maxAlive: 26,
    hunt: true,
  },
  // победа: на всех площадках флагов лежит по дружочку
  victory: { kind: 'flags', label: 'FLAGS' },
  // портал выхода — у того угла, где Герой (у выхода из форта), а не через полкольца
  exit: { room: 0, spots: around(760, 760, 0, 0).map(([x, y]) => [x, y]) },
  // часовых надо где-то брать: дружочки ждут чаще и их больше разом, профессии — тоже
  padSpawn: { jobs: { maxActive: 5, interval: [4, 9] } },
  allySpawn: { maxActive: 4, interval: [5, 10] },
  rooms: [ROOM_PLAN],
};
})(window.Game = window.Game || {});
