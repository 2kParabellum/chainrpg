//  Координаты — пиксели внутреннего прямоугольника уровня (units: 'px'): 0..2288 по обеим осям.
//  Сам зал — квадрат x 264..2024, y 264..2024 (центр — 1144, 1144) со срезанными углами; всё, что вокруг него, —
//  сплошная стена, кроме четырёх отростков посередине сторон (шириной 352, глубиной 264), в них — гнёзда врагов.
//  walls / pillars / pits: [cx, cy, w, h]; nests: [cx, cy]; pads: [cx, cy, ключ, { permanent }].
//  Пропасти разбросаны кольцом: не в центре (там спрут и его зона всасывания) и не у самых стен.
//  В левом нижнем и правом верхнем углах — постоянные подиумы «скорости» (не исчезают, взятый гаснет на 40 с), в двух других —
//  укрытия: угол отгорожен от центра стенками-колоннами, из-за них спрут не видит, в кого плюнуть.
