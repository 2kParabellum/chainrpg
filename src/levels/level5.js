'use strict';

// ============================================================================
//  ПЛАН ЗАЛА
//  Координаты — пиксели внутреннего прямоугольника уровня (units: 'px'): 0..2600 по обеим осям.
//  Сам зал — квадрат x 300..2300, y 300..2300 (центр — 1300, 1300) со срезанными углами; всё, что вокруг него, —
//  сплошная стена, кроме четырёх отростков посередине сторон (шириной 400, глубиной 300), в них — гнёзда врагов.
//  walls / pillars / pits: [cx, cy, w, h]; nests: [cx, cy]; pads: [cx, cy, ключ, { permanent }].
//  Пропасти разбросаны кольцом: не в центре (там спрут) и не у самых стен.
//  В левом нижнем и правом верхнем углах — постоянные подиумы «скорости» (никогда не исчезают), в двух других —
//  укрытия: угол отгорожен от центра стенками-колоннами, за ними можно спрятаться от пулемёта спрута.
// ============================================================================

const C = 1300;                  // центр зала
const LO = 300, HI = 2300;       // края зала
const CUT = 3, STEP = 70;        // срез угла — лесенка из CUT ступенек по STEP

// срез угла зала лесенкой: (x, y) — угол, (sx, sy) — куда от него внутрь зала; результат — стены [cx, cy, w, h]
function chamfer(x, y, sx, sy) {
  const out = [];
  for (let k = 0; k < CUT; k++) {
    const w = (CUT - k) * STEP;
    out.push([x + (sx * w) / 2, y + sy * (k + 0.5) * STEP, w, STEP]);
  }
  return out;
}

// укрытие в углу (x, y): две стенки буквой Г, загораживающие угол от центра; входы — вдоль стен зала
function shelter(x, y, sx, sy) {
  return [
    [x + sx * 295, y + sy * 440, 330, 40],   // поперёк, на 440 от угла
    [x + sx * 440, y + sy * 275, 40, 290],   // вдоль, на 440 от угла
  ];
}

