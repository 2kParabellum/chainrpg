// ============================================================================
//  ПЛАН ЗАЛА
//  Координаты — пиксели внутреннего прямоугольника уровня (units: 'px'): 0..2080 по обеим осям.
//  Сам зал — квадрат x 240..1840, y 240..1840 (центр — 1040, 1040) со срезанными углами; всё, что вокруг него, —
//  сплошная стена, кроме четырёх отростков посередине сторон (шириной 320, глубиной 240), в них — гнёзда врагов.
//  walls / pillars / pits: [cx, cy, w, h]; nests: [cx, cy]; pads: [cx, cy, ключ, { permanent }].
//  Пропасти разбросаны кольцом: не в центре (там спрут и его зона всасывания) и не у самых стен.
//  В левом нижнем и правом верхнем углах — постоянные подиумы «скорости» (никогда не исчезают), в двух других —
//  укрытия: угол отгорожен от центра стенками-колоннами, из-за них спрут не видит, в кого плюнуть.
// ============================================================================

const C = 1040;                  // центр зала
const LO = 240, HI = 1840;       // края зала
const CUT = 3, STEP = 56;        // срез угла — лесенка из CUT ступенек по STEP

// срез угла зала лесенкой: (x, y) — угол, (sx, sy) — куда от него внутрь зала; результат — стены [cx, cy, w, h]
function chamfer(x, y, sx, sy) {
  const out = [];
  for (let k = 0; k < CUT; k++) {
    const w = (CUT - k) * STEP;
    out.push([x + (sx * w) / 2, y + sy * (k + 0.5) * STEP, w, STEP]);
  }
  return out;
}

// укрытие в углу (x, y): две стенки буквой Г, загораживающие угол от центра; входы — вдоль стен зала
function shelter(x, y, sx, sy) {
  return [
    [x + sx * 236, y + sy * 352, 264, 40],   // поперёк, на 352 от угла
    [x + sx * 352, y + sy * 220, 40, 232],   // вдоль, на 352 от угла
  ];
}

