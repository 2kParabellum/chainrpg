// Данные уровня «Seal the Gates»: квадратный зал, в углах — четыре гнезда, рядом с каждым — площадка флага. Дружочек,
// пролежавший на флаге seals.time секунд, закрывает гнездо рядом; часового не стало — гнездо снова открыто. Поток врагов
// общий (waves.share): чем меньше открытых гнёзд, тем больше врагов выходит из каждого оставшегося. Закрыты все
// четыре разом — победа. Здесь только данные — никакой игровой логики (флаги и заслонки — game/flags.js, волны —
// game/waves.js).
(function (G) {
'use strict';

// ============================================================================
//  ПЛАН ЗАЛА
//  Координаты — пиксели внутреннего квадрата (units: 'px'): 0..2800 по обеим осям, центр — (1400, 1400).
//  pillars / pits / spikes: [cx, cy, w, h]; nests / flags: [cx, cy].
//  План симметричен поворотом на четверть оборота: всё, что задано для северо-западного угла и северной стороны,
//  повторяется помощником around() на остальных трёх.
//  Угол: гнездо в самом углу, флаг — на диагонали, ближе к центру. Двор угла отгорожен от центра «скобкой» — двумя
//  стенками-колоннами, сходящимися на диагонали; входы во двор — вдоль наружных стен. Сторона: посередине — пропасть
//  вдоль стены (у стены остаётся проход), ближе к углам — колонны-укрытия. Центр: каменный блок, по его сторонам — шипы.
// ============================================================================

const S = 2800, C = S / 2;

// четыре прямоугольника, симметричные (x, y) поворотом зала на четверть оборота: [cx, cy, w, h]
function around(x, y, w, h) {
  return [[x, y, w, h], [S - y, x, h, w], [S - x, S - y, w, h], [y, S - x, h, w]];
}
const points = (x, y) => around(x, y, 0, 0).map(([px, py]) => [px, py]);

const ROOM_PLAN = {
  units: 'px',
  pillars: [
    // скобка двора: стенка вдоль северного входа и стенка вдоль западного, сходятся на диагонали
    ...around(860, 690, 40, 380), ...around(690, 860, 380, 40),
    // укрытия по бокам от пропасти, ближе к углам
    ...around(1060, 400, 90, 90), ...around(S - 1060, 400, 90, 90),
    // центральный блок
    [C, C, 240, 240],
  ],
  // пропасть посередине стороны: между ней и стеной — проход шириной 340
  pits: around(C, 400, 360, 120),
  // шипы вплотную к сторонам центрального блока (его углы свободны)
  spikes: around(C, C - 150, 240, 60),
  // гнёзда — в самых углах
  nests: points(230, 230),
  // площадки флагов — на диагонали от гнезда к центру; флаг закрывает ближайшее к нему гнездо (см. game/flags.js)
  flags: points(520, 520),
};

G.level8 = {
  name: 'Seal the Gates',
  blurb: 'A square hall: four nests in the corners, a flag by each one',
  goal: 'Leave a mate on the flag by a nest to seal it — seal all four. Fewer gates, bigger waves',
  geometry: { kind: 'rect', width: S + 80, height: S + 80, wall: 40 },
  spawn: { room: 0, at: [C, 1900], heading: Math.PI }, // к югу от центра, лицом к юго-западному двору
  // враги гнёзд — подвижные типы, как в «Capture the Flags»; Скорпион (утаскивает часовых с флагов) — редкий
  enemyPool: ['shooter', 'bull', 'scorpion', 'zombie', 'hunter'],
  enemyWeights: { shooter: 4, zombie: 2, hunter: 2, bull: 1, scorpion: 0.5 },
  zoneNames: ['GATE HALL'],
  // гнёзда: по одному врагу, второй — с шестой волны гнезда; пауза между волнами гнезда всё время 24 с.
  // share — поток общий: закрытое гнездо отдаёт свою долю открытым (из каждого открытого — в «всего / открыто» раз
  // больше). hunt — враги волн идут к ближайшему союзнику: часовых на флагах грызут
  waves: {
    firstAt: 18, stagger: 6, interval: 24,
    size: { first: 1, grow: 0.2 },
    kinds: 2,
    spawnRadius: 90,
    telegraph: 4,
    maxAlive: 28,
    hunt: true,
    share: true,
  },
  // флаг закрывает ближайшее гнездо: часовой пролежал на площадке time секунд — гнездо закрыто, пока он там лежит
  seals: { time: 5 },
  // победа: закрыты все гнёзда разом
  victory: { kind: 'seals', label: 'GATES' },
  // портал выхода — у того двора, где Герой (у сгиба скобки), а не через весь зал
  exit: { room: 0, spots: points(720, 720) },
  // часовых надо где-то брать: дружочки ждут чаще и их больше разом, профессии — тоже
  padSpawn: { jobs: { maxActive: 5, interval: [4, 9] } },
  allySpawn: { maxActive: 4, interval: [5, 10] },
  rooms: [ROOM_PLAN],
};
})(window.Game = window.Game || {});
