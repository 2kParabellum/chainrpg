const T = 40; // толщина стен

// отрезок a..b без промежутков gaps ([[от, до], ...]) — куски стены между дверями
function cut(a, b, gaps = []) {
  const out = [];
  let from = a;
  for (const [g0, g1] of gaps.slice().sort((p, q) => p[0] - q[0])) {
    if (g0 > from) out.push([from, g0]);
    from = Math.max(from, g1);
  }
  if (b > from) out.push([from, b]);
  return out;
}

// стены «здания» по осям x0..x1, y0..y1 с дверями: doors.top / doors.bottom — промежутки по x,
// doors.left / doors.right — промежутки по y; результат — прямоугольники стен [cx, cy, w, h] для pillars
function building(x0, y0, x1, y1, doors) {
  const out = [];
  const horiz = (y, gaps) => cut(x0 - T / 2, x1 + T / 2, gaps).forEach(([a, b]) => out.push([(a + b) / 2, y, b - a, T]));
  const vert = (x, gaps) => cut(y0 + T / 2, y1 - T / 2, gaps).forEach(([a, b]) => out.push([x, (a + b) / 2, T, b - a]));
  horiz(y0, doors.top); horiz(y1, doors.bottom); vert(x0, doors.left); vert(x1, doors.right);
  return out;
}

